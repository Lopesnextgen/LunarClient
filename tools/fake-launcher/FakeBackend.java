    static final class AssetServer extends WebSocketServer {

        AssetServer(int port) {
            super(new InetSocketAddress("127.0.0.1", port));
        }

        @Override
        public void onOpen(WebSocket conn, ClientHandshake handshake) {
            line("asset: connection from " + conn.getRemoteSocketAddress());
        }

        @Override
        public void onClose(WebSocket conn, int code, String reason, boolean remote) {
            line("asset: closed " + code + " " + reason);
            relays.remove(conn);
        }

        @Override
        public void onMessage(WebSocket conn, String message) {
            line("asset: unexpected text frame");
        }

        @Override
        public void onMessage(WebSocket conn, ByteBuffer buffer) {
            byte[] bytes = new byte[buffer.remaining()];
            buffer.duplicate().get(bytes);

            WebSocketClient relay = relays.get(conn);
            if (relay != null) {
                if (relay.isOpen()) {
                    relay.send(bytes);
                } else {
                    relays.remove(conn);
                }
                return;
            }

            if (conn.getAttachment() == null) {
                // first frame: raw Handshake protobuf identifying the player
                String username = null;
                try {
                    com.lunarclient.websocket.handshake.v1.Handshake parsed =
                            com.lunarclient.websocket.handshake.v1.Handshake.parseFrom(bytes);
                    if (parsed.hasIdentity() && parsed.getIdentity().hasPlayer()) {
                        username = parsed.getIdentity().getPlayer().getUsername();
                    }
                } catch (Exception exception) {
                    line("asset: unparsed first frame (" + bytes.length + "B)");
                }
                if (username != null && isOfficial(username)) {
                    line("asset: " + username + " is an official session -> Lunar backend");
                    final byte[] handshake = bytes;
                    final String playerName = username;
                    WebSocketClient upstream = new WebSocketClient(URI.create(OFFICIAL_ASSET), new Draft_6455(),
                            Map.of("Accept", "application/x-protobuf",
                                    "User-Agent", "Lunar Client 2.22.35-2637"), 30000) {
                        @Override
                        public void onOpen(ServerHandshake serverHandshake) {
                            line("asset(official): connected, forwarding handshake for " + playerName);
                            send(handshake);
                        }

                        @Override
                        public void onMessage(ByteBuffer message) {
                            byte[] copy = new byte[message.remaining()];
                            message.duplicate().get(copy);
                            if (conn.isOpen()) {
                                conn.send(copy);
                            }
                        }

                        @Override
                        public void onMessage(String message) {
                        }

                        @Override
                        public void onClose(int code, String reason, boolean remote) {
                            line("asset(official): closed " + code + " " + reason);
                            relays.remove(conn);
                            if (conn.isOpen()) {
                                conn.close(code == 1000 ? 1000 : 1011, reason);
                            }
                        }

                        @Override
                        public void onError(Exception exception) {
                            line("asset(official): error " + exception);
                        }
                    };
                    relays.put(conn, upstream);
                    if (upstream.connectBlocking(CONNECT_TIMEOUT_SECONDS, TimeUnit.SECONDS)) {
                        conn.setAttachment(Boolean.TRUE);
                    } else {
                        line("asset: official connect timed out, serving locally");
                        relays.remove(conn);
                        conn.setAttachment(Boolean.FALSE);
                    }
                    return;
                }
                conn.setAttachment(Boolean.FALSE);
                return; // handshake consumed; local mode
            }

            if (Boolean.TRUE.equals(conn.getAttachment())) {
                return; // relay path handled above
            }

            // ---- local mode ------------------------------------------------
            com.lunarclient.websocket.protocol.v1.ServerboundWebSocketMessage request;
            try {
                request = com.lunarclient.websocket.protocol.v1.ServerboundWebSocketMessage.parseFrom(bytes);
            } catch (Exception exception) {
                line("asset: unparseable frame (" + bytes.length + "B)");
                return;
            }
            String service = request.getService();
            String method = request.getMethod();
            ByteString output = respond(service, method, request.getInput());
            line("asset: local RPC " + shortService(service) + "." + method
                    + " id=" + request.getRequestId().toStringUtf8()
                    + " in=" + request.getInput().size() + "B out=" + output.size() + "B");
            conn.send(com.lunarclient.websocket.protocol.v1.ClientboundWebSocketMessage.newBuilder()
                    .setRpcResponse(WebSocketRpcResponse.newBuilder()
                            .setRequestId(request.getRequestId())
                            .setOutput(output)
                            .build())
                    .build().toByteArray());
        }

        private static ByteString respond(String service, String method, ByteString input) {
            try {
                // The RPC method string keeps the proto name ("Login",
                // "CreateOutfit", ...), so match it case-insensitively: an
                // exact "login" comparison used to fall through and answer
                // EMPTY, which left cosmetics/discovery completely unloaded.
                String rpc = method == null ? "" : method.toLowerCase(java.util.Locale.ROOT);
                if ("lunarclient.websocket.serverdiscovery.v1.ServerDiscoveryService".equals(service)) {
                    return discoveryRpc(rpc, input);
                }
                if ("lunarclient.websocket.cosmetic.v2.CosmeticService".equals(service)) {
                    return cosmeticRpc(rpc, input);
                }
                if (!"login".equals(rpc)) {
                    return ByteString.EMPTY;
                }
                switch (service) {
                    case "lunarclient.websocket.emote.v1.EmoteService":
                        return com.lunarclient.websocket.emote.v1.LoginResponse.newBuilder()
                                .setHasAllEmotesFlag(true)
                                .build().toByteString();
                    case "lunarclient.websocket.spray.v1.SprayService":
                        return com.lunarclient.websocket.spray.v1.LoginResponse.newBuilder()
                                .setHasAllSpraysFlag(true)
                                .build().toByteString();
                    case "lunarclient.websocket.badge.v1.BadgeService":
                        return com.lunarclient.websocket.badge.v1.LoginResponse.newBuilder()
                                .setHasAllBadgesFlag(true)
                                .build().toByteString();
                    case "lunarclient.websocket.store.v1.StoreService":
                        return com.lunarclient.websocket.store.v1.LoginResponse.newBuilder()
                                .setCoins(1000000L)
                                .build().toByteString();
                    default:
                        return ByteString.EMPTY;
                }
            } catch (Throwable throwable) {
                line("asset: response error for " + service + "." + method + ": " + throwable);
                return ByteString.EMPTY;
            }
        }

        /**
         * Local cosmetics: has-all flags plus one editable "Default" outfit.
         *
         * The outfit matters beyond the locker UI: OutfitManager lazily builds
         * a player's conditional outfit tree and reads
         * {@code defaultTree.getCurrentOutfit().getBadgeId()} without checking
         * getCurrentOutfit() for null, so a login response without a default
         * outfit NPEs the moment an outfit is requested (opening the
         * cosmetics drawer does exactly that).
         */
        private static ByteString cosmeticRpc(String method, ByteString input) {
            switch (method) {
                case "login": {
                    com.lunarclient.websocket.cosmetic.v2.Outfit defaultOutfit =
                            com.lunarclient.websocket.cosmetic.v2.Outfit.newBuilder()
                                    .setId(localUuid())
                                    .setName("Default")
                                    .setFavorite(true)
                                    .build();
                    return com.lunarclient.websocket.cosmetic.v2.LoginResponse.newBuilder()
                            .setHasAllCosmeticsFlag(true)
                            .addOutfits(defaultOutfit)
                            .setOutfitTree(com.lunarclient.websocket.cosmetic.v2.OutfitTree.newBuilder()
                                    .setDefaultOutfitId(localUuid())
                                    .build())
                            .build().toByteString();
                }
                case "createoutfit": {
                    com.lunarclient.websocket.cosmetic.v2.CreateOutfitRequest request =
                            com.lunarclient.websocket.cosmetic.v2.CreateOutfitRequest.parseFrom(input);
                    com.lunarclient.websocket.cosmetic.v2.Outfit outfit =
                            com.lunarclient.websocket.cosmetic.v2.Outfit.newBuilder()
                                    .setId(uuid(java.util.UUID.randomUUID()))
                                    .setName(request.getName())
                                    .build();
                    return com.lunarclient.websocket.cosmetic.v2.CreateOutfitResponse.newBuilder()
                            .setStatus(com.lunarclient.websocket.cosmetic.v2.CreateOutfitResponse.Status.STATUS_OK)
                            .setOutfit(outfit)
                            .build().toByteString();
                }
                case "updateoutfit": {
                    com.lunarclient.websocket.cosmetic.v2.UpdateOutfitRequest request =
                            com.lunarclient.websocket.cosmetic.v2.UpdateOutfitRequest.parseFrom(input);
                    return com.lunarclient.websocket.cosmetic.v2.UpdateOutfitResponse.newBuilder()
                            .setStatus(com.lunarclient.websocket.cosmetic.v2.UpdateOutfitResponse.Status.STATUS_OK)
                            .setOutfit(request.getOutfit())
                            .build().toByteString();
                }
                case "deleteoutfit":
                    return com.lunarclient.websocket.cosmetic.v2.DeleteOutfitResponse.newBuilder()
                            .setStatus(com.lunarclient.websocket.cosmetic.v2.DeleteOutfitResponse.Status.STATUS_OK)
                            .build().toByteString();
                case "selectoutfit":
                    return com.lunarclient.websocket.cosmetic.v2.SelectOutfitResponse.newBuilder()
                            .setStatus(com.lunarclient.websocket.cosmetic.v2.SelectOutfitResponse.Status.STATUS_OK)
                            .build().toByteString();
                case "favoritecosmetic":
                case "unfavoritecosmetic":
                    return ByteString.EMPTY;
                default:
                    return ByteString.EMPTY;
            }
        }

        private static String shortService(String service) {
            int index = service.lastIndexOf('.');
            return index == -1 ? service : service.substring(index + 1);
        }

        @Override
        public void onError(WebSocket conn, Exception exception) {
            line("asset: error " + exception);
        }

        @Override
        public void onStart() {
            line("asset: server started");
        }
    }
