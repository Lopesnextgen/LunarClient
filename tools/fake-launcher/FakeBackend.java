    public static void main(String[] args) throws Exception {
        int assetPort = args.length > 0 ? Integer.parseInt(args[0]) : 28191;
        int authPort = args.length > 1 ? Integer.parseInt(args[1]) : 28192;
        Path logFile = Paths.get(args.length > 2 ? args[2] : "run/logs/fake-backend.log");
        accountsFile = args.length > 3 ? Paths.get(args[3]) : null;
        Files.createDirectories(logFile.getParent());
        log = new PrintWriter(new FileWriter(logFile.toFile(), true), true);
        discovery = loadDiscovery(args.length > 4 ? Paths.get(args[4]) : null);

        new AuthenticatorServer(authPort).start();
        new AssetServer(assetPort).start();
        line("fake backend listening: authenticator=:" + authPort + " asset=:" + assetPort
                + (accountsFile == null ? "" : " accounts=" + accountsFile));
        line("official proxy: premium accounts -> " + OFFICIAL_AUTH + " / " + OFFICIAL_ASSET);
        Thread.sleep(Long.MAX_VALUE);
    }

    static void line(String text) {
        String msg = "[" + LocalTime.now().withNano(0) + "] " + text;
        System.out.println(msg);
        if (log != null) {
            log.println(msg);
        }
    }

    /** True when accounts.json has this player as a real (non-offline) account. */
    static boolean isPremium(String username) {
        if (username == null || accountsFile == null || !Files.isRegularFile(accountsFile)) {
            return false;
        }
        try {
            String text = new String(Files.readAllBytes(accountsFile), StandardCharsets.UTF_8);
            JsonObject root = new JsonParser().parse(text).getAsJsonObject();
            if (!root.has("accounts")) {
                return false;
            }
            for (Map.Entry<String, JsonElement> entry : root.getAsJsonObject("accounts").entrySet()) {
                JsonObject account = entry.getValue().getAsJsonObject();
                String name = account.has("username") ? account.get("username").getAsString() : "";
                if (!name.equalsIgnoreCase(username)) {
                    continue;
                }
                String token = account.has("accessToken") ? account.get("accessToken").getAsString() : "";
                String refresh = account.has("refreshToken") ? account.get("refreshToken").getAsString() : "";
                return !token.endsWith(".offline") && !refresh.startsWith("local-offline-");
            }
        } catch (Exception exception) {
            line("accounts.json read failed: " + exception);
        }
        return false;
    }

    static void markOfficial(String username) {
        if (username != null) {
            officialSessions.put(username.toLowerCase(), Boolean.TRUE);
        }
    }

    static boolean isOfficial(String username) {
        return username != null && officialSessions.containsKey(username.toLowerCase());
    }

    static byte[] localAuthSuccess(String username) {
        Base64.Encoder encoder = Base64.getUrlEncoder().withoutPadding();
        String header = encoder.encodeToString(
                "{\"alg\":\"none\",\"typ\":\"JWT\"}".getBytes(StandardCharsets.UTF_8));
        long exp = System.currentTimeMillis() / 1000L + 30L * 24L * 3600L;
        String payload = encoder.encodeToString(
                ("{\"sub\":\"" + username + "\",\"name\":\"" + username + "\",\"exp\":" + exp + "}")
                        .getBytes(StandardCharsets.UTF_8));
        String jwt = header + "." + payload + ".local-dev";
        return com.lunarclient.authenticator.v1.ClientboundWebSocketMessage.newBuilder()
                .setAuthSuccess(AuthSuccessMessage.newBuilder().setJwt(jwt).build())
                .build().toByteArray();
    }

