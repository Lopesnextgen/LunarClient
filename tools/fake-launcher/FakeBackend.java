    static final class AuthenticatorServer extends WebSocketServer {

        AuthenticatorServer(int port) {
            super(new InetSocketAddress("127.0.0.1", port));
        }

        @Override
        public void onOpen(WebSocket conn, ClientHandshake handshake) {
            line("auth: connection from " + conn.getRemoteSocketAddress());
        }

        @Override
        public void onClose(WebSocket conn, int code, String reason, boolean remote) {
            line("auth: closed " + code + " " + reason);
            relays.remove(conn);
        }

        @Override
        public void onMessage(WebSocket conn, String message) {
            line("auth: unexpected text frame");
        }

        @Override
        public void onMessage(WebSocket conn, ByteBuffer buffer) {
            byte[] bytes = new byte[buffer.remaining()];
            buffer.duplicate().get(bytes);

            WebSocketClient relay = relays.get(conn);
            if (relay != null) {
                if (relay.isOpen()) {
                    relay.send(bytes);
                } else {
                    relays.remove(conn);
                }
                return;
            }

            com.lunarclient.authenticator.v1.ServerboundWebSocketMessage request;
            try {
                request = com.lunarclient.authenticator.v1.ServerboundWebSocketMessage.parseFrom(bytes);
            } catch (Exception exception) {
                line("auth: unparseable frame (" + bytes.length + "B)");
                return;
            }
            if (!request.hasHello()) {
                line("auth: unhandled " + request.getContentsCase());
                return;
            }
            String username = request.getHello().getIdentity().getUsername();
            if (isPremium(username)) {
                line("auth: " + username + " is premium -> official authenticator");
                final byte[] hello = bytes;
                WebSocketClient upstream = new WebSocketClient(URI.create(OFFICIAL_AUTH), new Draft_6455(),
                        Map.of("Accept", "application/x-protobuf",
                                "User-Agent", "Lunar Client 2.22.35-2637"), 30000) {
                    @Override
                    public void onOpen(ServerHandshake handshake) {
                        line("auth(official): connected, forwarding hello for " + username);
                        send(hello);
                    }

                    @Override
                    public void onMessage(ByteBuffer message) {
                        byte[] copy = new byte[message.remaining()];
                        message.duplicate().get(copy);
                        try {
                            com.lunarclient.authenticator.v1.ClientboundWebSocketMessage inbound =
                                    com.lunarclient.authenticator.v1.ClientboundWebSocketMessage.parseFrom(copy);
                            if (inbound.hasAuthSuccess()) {
                                markOfficial(username);
                                line("auth(official): authSuccess for " + username);
                            }
                        } catch (Exception ignored) {
                            // relay anyway
                        }
                        if (conn.isOpen()) {
                            conn.send(copy);
                        }
                    }

                    @Override
                    public void onMessage(String message) {
                    }

                    @Override
                    public void onClose(int code, String reason, boolean remote) {
                        line("auth(official): closed " + code + " " + reason);
                        relays.remove(conn);
                        if (conn.isOpen() && !isOfficial(username)) {
                            // official auth failed (expired token, no purchase, ...)
                            line("auth: official session failed for " + username + ", fallback local");
                            conn.send(localAuthSuccess(username));
                        }
                    }

                    @Override
                    public void onError(Exception exception) {
                        line("auth(official): error " + exception);
                    }
                };
                relays.put(conn, upstream);
                if (!upstream.connectBlocking(CONNECT_TIMEOUT_SECONDS, TimeUnit.SECONDS)) {
                    line("auth: official connect timed out, fallback local");
                    relays.remove(conn);
                    conn.send(localAuthSuccess(username));
                }
                return;
            }
            line("auth: " + username + " is cracked -> local session");
            conn.send(localAuthSuccess(username));
        }

        @Override
        public void onError(WebSocket conn, Exception exception) {
            line("auth: error " + exception);
        }

        @Override
        public void onStart() {
            line("auth: server started");
        }
    }

