    private static Discovery loadDiscovery(Path file) {
        Discovery result = new Discovery();
        if (file == null || !Files.isRegularFile(file)) {
            line("discovery: no catalogue at " + file + ", Discover will be empty");
            return result;
        }
        try {
            String text = new String(Files.readAllBytes(file), StandardCharsets.UTF_8);
            JsonObject root = new JsonParser().parse(text).getAsJsonObject();
            result.totalServers = root.has("totalServers") ? root.get("totalServers").getAsInt() : 0;
            if (root.has("gameTypes")) {
                for (JsonElement element : root.getAsJsonArray("gameTypes")) {
                    JsonObject type = element.getAsJsonObject();
                    String name = type.get("name").getAsString();
                    result.gameTypes.add(name);
                    result.gameTypeIcons.put(name, type.has("emoji") ? type.get("emoji").getAsString() : "");
                }
            }
            if (root.has("sections")) {
                for (JsonElement element : root.getAsJsonArray("sections")) {
                    JsonObject section = element.getAsJsonObject();
                    SectionEntry entry = new SectionEntry();
                    entry.id = section.get("id").getAsString();
                    entry.name = section.get("name").getAsString();
                    entry.description = section.has("description") ? section.get("description").getAsString() : "";
                    entry.cardSize = section.has("cardSize") ? section.get("cardSize").getAsString() : "medium";
                    entry.emoji = section.has("emoji") ? section.get("emoji").getAsString() : "";
                    for (JsonElement id : section.getAsJsonArray("serverIds")) {
                        entry.serverIds.add(id.getAsString());
                    }
                    result.sections.add(entry);
                }
            }
            if (root.has("servers")) {
                for (Map.Entry<String, JsonElement> element : root.getAsJsonObject("servers").entrySet()) {
                    JsonObject server = element.getValue().getAsJsonObject();
                    ServerEntry entry = new ServerEntry();
                    entry.name = server.get("name").getAsString();
                    entry.description = server.has("description") ? server.get("description").getAsString() : "";
                    entry.primaryAddress = server.has("primaryAddress") ? server.get("primaryAddress").getAsString() : "";
                    entry.primaryColor = server.has("primaryColor") ? server.get("primaryColor").getAsString() : "";
                    entry.logoUrl = server.has("logoUrl") && !server.get("logoUrl").isJsonNull()
                            ? server.get("logoUrl").getAsString() : "";
                    entry.backgroundUrl = server.has("backgroundUrl") && !server.get("backgroundUrl").isJsonNull()
                            ? server.get("backgroundUrl").getAsString() : "";
                    addStrings(entry.addresses, server.getAsJsonArray("addresses"));
                    addStrings(entry.gameTypes, server.getAsJsonArray("gameTypes"));
                    addStrings(entry.regions, server.getAsJsonArray("regions"));
                    if (server.has("socials")) {
                        for (Map.Entry<String, JsonElement> social : server.getAsJsonObject("socials").entrySet()) {
                            if (!social.getValue().isJsonNull()) {
                                entry.socials.put(social.getKey(), social.getValue().getAsString());
                            }
                        }
                    }
                    result.servers.put(element.getKey(), entry);
                }
            }
            line("discovery: loaded " + result.servers.size() + " servers / "
                    + result.sections.size() + " sections from " + file);
        } catch (Throwable throwable) {
            line("discovery: failed to read " + file + ": " + throwable);
        }
        return result;
    }

    private static void addStrings(java.util.List<String> target, com.google.gson.JsonArray source) {
        if (source != null) {
            for (JsonElement element : source) {
                target.add(element.getAsString());
            }
        }
    }

    private static ByteString discoveryRpc(String method, ByteString input) {
        // `method` is the lower-cased proto RPC name.
        switch (method) {
            case "login": {
                com.lunarclient.websocket.serverdiscovery.v1.LoginResponse.Builder response =
                        com.lunarclient.websocket.serverdiscovery.v1.LoginResponse.newBuilder()
                                .setTotalServers(discovery.totalServers);
                for (String gameType : discovery.gameTypes) {
                    response.addGameTypes(gameType(gameType));
                }
                return response.build().toByteString();
            }
            case "discoverservers": {
                DiscoverServersResponse.Builder response = DiscoverServersResponse.newBuilder();
                for (SectionEntry section : discovery.sections) {
                    ServerSection.Builder builder = ServerSection.newBuilder()
                            .setId(section.id)
                            .setName(section.name)
                            .setDescription(section.description)
                            .setEmoji(section.emoji)
                            .setCardSize("large".equals(section.cardSize)
                                    ? ServerSection.CardSize.CARD_SIZE_LARGE
                                    : ServerSection.CardSize.CARD_SIZE_MEDIUM);
                    for (String id : section.serverIds) {
                        ServerEntry server = discovery.servers.get(id);
                        if (server == null) {
                            continue;
                        }
                        builder.addCards(card(id, server, "featured".equals(section.id)));
                    }
                    response.addSections(builder);
                }
                return response.build().toByteString();
            }
            case "searchservers": {
                SearchServersRequest request = SearchServersRequest.parseFrom(input);
                String query = request.getQuery().trim().toLowerCase(java.util.Locale.ROOT);
                SearchServersResponse.Builder response = SearchServersResponse.newBuilder();
                if (!query.isEmpty()) {
                    for (Map.Entry<String, ServerEntry> entry : discovery.servers.entrySet()) {
                        if (!matches(entry.getKey(), entry.getValue(), query)) {
                            continue;
                        }
                        response.addServers(card(entry.getKey(), entry.getValue(), false));
                        if (response.getServersCount() >= 30) {
                            break;
                        }
                    }
                }
                return response.build().toByteString();
            }
            case "loadautocompletesuggestions": {
                LoadAutocompleteSuggestionsResponse.Builder response =
                        LoadAutocompleteSuggestionsResponse.newBuilder();
                for (ServerEntry server : discovery.servers.values()) {
                    AutocompleteSuggestion.Builder suggestion = AutocompleteSuggestion.newBuilder()
                            .setName(server.name)
                            .setPrimaryAddress(server.primaryAddress);
                    for (String address : server.addresses) {
                        suggestion.addAddresses(address);
                    }
                    response.addSuggestions(suggestion);
                }
                return response.build().toByteString();
            }
            case "loadservermodal": {
                LoadServerModalRequest request = LoadServerModalRequest.parseFrom(input);
                ServerEntry server = discovery.servers.get(request.getServerMappingsId());
                if (server == null) {
                    return ByteString.EMPTY;
                }
                ServerModalDetails.Builder details = ServerModalDetails.newBuilder()
                        .setDescription(server.description);
                put(details, server.socials, "twitter");
                put(details, server.socials, "discord");
                put(details, server.socials, "youtube");
                put(details, server.socials, "instagram");
                put(details, server.socials, "twitch");
                put(details, server.socials, "telegram");
                put(details, server.socials, "reddit");
                put(details, server.socials, "tiktok");
                put(details, server.socials, "facebook");
                return LoadServerModalResponse.newBuilder().setDetails(details).build().toByteString();
            }
            case "tracksectionnotinterested":
            case "trackserverjoin":
            default:
                return ByteString.EMPTY;
        }
    }

    private static void put(ServerModalDetails.Builder details, Map<String, String> socials, String key) {
        String value = socials.get(key);
        if (value == null || value.isEmpty()) {
            return;
        }
        switch (key) {
            case "twitter" -> details.setTwitter(value);
            case "discord" -> details.setDiscord(value);
            case "youtube" -> details.setYoutube(value);
            case "instagram" -> details.setInstagram(value);
            case "twitch" -> details.setTwitch(value);
            case "telegram" -> details.setTelegram(value);
            case "reddit" -> details.setReddit(value);
            case "tiktok" -> details.setTiktok(value);
            case "facebook" -> details.setFacebook(value);
            default -> {
            }
        }
    }

    private static boolean matches(String id, ServerEntry server, String query) {
        if (id.toLowerCase(java.util.Locale.ROOT).contains(query)
                || server.name.toLowerCase(java.util.Locale.ROOT).contains(query)
                || server.primaryAddress.toLowerCase(java.util.Locale.ROOT).contains(query)) {
            return true;
        }
        for (String address : server.addresses) {
            if (address.toLowerCase(java.util.Locale.ROOT).contains(query)) {
                return true;
            }
        }
        for (String gameType : server.gameTypes) {
            if (gameType.toLowerCase(java.util.Locale.ROOT).contains(query)) {
                return true;
            }
        }
        return false;
    }

    private static ServerGameType gameType(String name) {
        return ServerGameType.newBuilder()
                .setName(name)
                .setEmoji(discovery.gameTypeIcons.getOrDefault(name, ""))
                .build();
    }

    private static ServerCard card(String id, ServerEntry server, boolean featured) {
        ServerCard.Builder builder = ServerCard.newBuilder()
                .setRecommendationId(id)
                .setServerMappingsId(id)
                .setName(server.name)
                .setPrimaryAddress(server.primaryAddress)
                .setBadge(featured ? ServerCard.Badge.BADGE_FEATURED : ServerCard.Badge.BADGE_UNSPECIFIED)
                .addAllRegionCodes(server.regions);
        if (!server.logoUrl.isEmpty()) {
            builder.setLogoUrl(server.logoUrl);
        }
        if (!server.backgroundUrl.isEmpty()) {
            builder.setBackgroundUrl(server.backgroundUrl);
        }
        int color = parseColor(server.primaryColor);
        if (color != 0) {
            builder.setPrimaryColor(Color.newBuilder().setColor(color));
        }
        for (String gameType : server.gameTypes) {
            builder.addGameTypes(gameType(gameType));
        }
        return builder.build();
    }

    /** Stable id for the offline account's default outfit. */
    private static final java.util.UUID LOCAL_OUTFIT_ID =
            java.util.UUID.fromString("00000000-0000-0000-0000-000000000001");

    private static com.lunarclient.common.v1.Uuid localUuid() {
        return uuid(LOCAL_OUTFIT_ID);
    }

    private static com.lunarclient.common.v1.Uuid uuid(java.util.UUID id) {
        return com.lunarclient.common.v1.Uuid.newBuilder()
                .setHigh64(id.getMostSignificantBits())
                .setLow64(id.getLeastSignificantBits())
                .build();
    }

    /** "#RRGGBB" (official mapping format) -> 0xRRGGBB. */
    private static int parseColor(String value) {
        if (value == null || value.isEmpty()) {
            return 0;
        }
        try {
            return Integer.parseInt(value.startsWith("#") ? value.substring(1) : value, 16) & 0xFFFFFF;
        } catch (NumberFormatException ignored) {
            return 0;
        }
    }

